package com.vinnot.event.domain.valueobject;

/**
 * Enumeration of event types.
 */
public enum EventType {

    /**
     * Wine tasting event.
     */
    TASTING,

    /**
     * Wine festival.
     */
    FESTIVAL,

    /**
     * Vineyard tour.
     */
    TOUR,

    /**
     * Educational workshop.
     */
    WORKSHOP,

    /**
     * Educational class.
     */
    CLASS,

    /**
     * Wine dinner.
     */
    DINNER,

    /**
     * Wine pairing event.
     */
    PAIRING,

    /**
     * Wine competition.
     */
    COMPETITION,

    /**
     * Wine fair or exhibition.
     */
    FAIR,

    /**
     * Harvest event.
     */
    HARVEST,

    /**
     * Other wine-related event.
     */
    OTHER
}

