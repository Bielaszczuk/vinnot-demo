package com.vinnot.wine.domain.valueobject;

/**
 * Enumeration of wine types.
 */
public enum WineType {

    /**
     * Red wine.
     */
    RED,

    /**
     * White wine.
     */
    WHITE,

    /**
     * Rose wine.
     */
    ROSE,

    /**
     * Sparkling wine.
     */
    SPARKLING,

    /**
     * Dessert wine.
     */
    DESSERT,

    /**
     * Fortified wine.
     */
    FORTIFIED,

    /**
     * Orange wine (skin-contact white).
     */
    ORANGE
}

