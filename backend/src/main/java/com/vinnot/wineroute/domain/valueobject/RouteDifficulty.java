/**
 * Enumeration of route duration categories.
 */
public enum RouteDifficulty {

    /**
     * Short route, a few hours.
     */
    SHORT,

    /**
     * Medium length route, half day to full day.
     */
    MEDIUM,

    /**
     * Long route, multiple days.
     */
    LONG
}

