package com.vinnot.wineroute.domain.valueobject;

/**
 * Enumeration of wine route status.
 */
public enum RouteStatus {

    /**
     * Route is in draft mode.
     */
    DRAFT,

    /**
     * Route is published and visible.
     */
    PUBLISHED,

    /**
     * Route is archived.
     */
    ARCHIVED
}

