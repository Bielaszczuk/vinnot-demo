-- #489: social media agent, phase 1. A wine-day calendar with date rules (half of the days move every year),
-- the content pillars the weekly planner rotates, and the social posts waiting for the owner's approval.

CREATE TABLE wine_days (
    code         VARCHAR(64)  PRIMARY KEY,
    name_es      VARCHAR(120) NOT NULL,
    name_en      VARCHAR(120) NOT NULL,
    kind         VARCHAR(16)  NOT NULL CHECK (kind IN ('GRAPE', 'STYLE', 'PROFESSION', 'NATIONAL', 'GENERIC')),
    -- fixed:MM-DD | nth-weekday:MM:DOW:N | last-weekday:MM:DOW | offset-from:<rule>:<signed days>
    date_rule    VARCHAR(64)  NOT NULL,
    priority     SMALLINT     NOT NULL CHECK (priority BETWEEN 1 AND 3),
    country_code CHAR(2)
);

CREATE TABLE content_pillars (
    code       VARCHAR(32)  PRIMARY KEY,
    name_es    VARCHAR(120) NOT NULL,
    name_en    VARCHAR(120) NOT NULL,
    weight     SMALLINT     NOT NULL CHECK (weight >= 1),
    brief      TEXT         NOT NULL,
    sort_order SMALLINT     NOT NULL UNIQUE
);

CREATE TABLE social_posts (
    id            UUID         PRIMARY KEY,
    status        VARCHAR(20)  NOT NULL CHECK (status IN ('DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED',
                                                           'SCHEDULED', 'PUBLISHED', 'FAILED')),
    scheduled_for TIMESTAMPTZ  NOT NULL UNIQUE,
    language      VARCHAR(8)   NOT NULL DEFAULT 'es-AR',
    pillar_code   VARCHAR(32)  NOT NULL REFERENCES content_pillars (code),
    wine_day_code VARCHAR(64)  REFERENCES wine_days (code),
    copy          JSONB,
    generation    JSONB,
    reviewed_by   UUID         REFERENCES users (id) ON DELETE SET NULL,
    reviewed_at   TIMESTAMPTZ,
    review_reason TEXT,
    edited_by     UUID         REFERENCES users (id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_social_posts_status_scheduled ON social_posts (status, scheduled_for);
-- Every foreign key is indexed at its leading column (database index contract).
CREATE INDEX idx_social_posts_pillar_code ON social_posts (pillar_code);
CREATE INDEX idx_social_posts_wine_day_code ON social_posts (wine_day_code);
CREATE INDEX idx_social_posts_reviewed_by ON social_posts (reviewed_by);
CREATE INDEX idx_social_posts_edited_by ON social_posts (edited_by);

