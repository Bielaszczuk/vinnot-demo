import { act, renderHook } from "@testing-library/react-native";
import { usePermanentAccountDeletion } from "./usePermanentAccountDeletion";
const mockDelete = jest.fn();
const mockClear = jest.fn();
const mockApple = jest.fn();
const mockReplace = jest.fn();
const mockError = jest.fn();
let mockProviders: string[] = [];
let mockPhrase = "acepto borrar cuenta";
jest.mock("react-i18next", () => ({ useTranslation: () => ({ t: (key: string) => key === "profile.deleteAccountPhrase" ? mockPhrase : key }) }));
jest.mock("expo-router", () => ({ useRouter: () => ({ replace: mockReplace }) }));
jest.mock("@/presentation/hooks/useAuth", () => ({ useAuth: () => ({ user: { socialProviders: mockProviders }, clearSession: mockClear }) }));
jest.mock("@/presentation/hooks/useAccountActions", () => ({ useAccountActions: () => ({ acquireAppleAccountDeletionCredential: mockApple }) }));
jest.mock("@/presentation/hooks/queries/user", () => ({ useDeleteAccount: () => ({ mutateAsync: mockDelete }) }));
jest.mock("@/presentation/providers/ToastProvider", () => ({ useToast: () => ({ showError: mockError }) }));
beforeEach(() => {
  jest.resetAllMocks();
  mockPhrase = "acepto borrar cuenta";
  mockProviders = [];
  mockDelete.mockResolvedValue(undefined);
  mockClear.mockResolvedValue(undefined);
});
it.each(["acepto borrar cuenta", "I agree to delete my account"])("requires %s before deletion", async phrase => {
  mockPhrase = phrase;
  const deleted = jest.fn();
  const { result } = renderHook(() => usePermanentAccountDeletion(deleted));
  act(() => result.current.open());
  act(() => result.current.setText("delete"));
  await act(() => result.current.submit());
  expect(mockDelete).not.toHaveBeenCalled();
  act(() => result.current.setText(` ${phrase} `));
  await act(() => result.current.submit());
  expect(mockDelete).toHaveBeenCalledTimes(1);
  expect(mockDelete).toHaveBeenCalledWith({});
  expect(deleted).toHaveBeenCalledTimes(1);
  expect(mockClear).toHaveBeenCalledTimes(1);
  expect(mockReplace).toHaveBeenCalledWith("/(auth)/login");
});
it("cancels and resets without deleting", async () => {
  const { result } = renderHook(() => usePermanentAccountDeletion(jest.fn()));
  act(() => result.current.open());
  act(() => result.current.setText(mockPhrase));
  act(() => result.current.close());
  await act(() => result.current.submit());
  act(() => result.current.open());
  expect(result.current.text).toBe("");
  expect(mockDelete).not.toHaveBeenCalled();
});
it("locks dismissal and duplicate submission while Apple reauthorization is pending", async () => {
  mockProviders = ["APPLE"];
  let authorize!: (credential: { appleAuthorizationCode: string }) => void;
  mockApple.mockReturnValue(new Promise(resolve => { authorize = resolve; }));
  const { result } = renderHook(() => usePermanentAccountDeletion(jest.fn()));
  act(() => result.current.open());
  act(() => result.current.setText(mockPhrase));
  let pending!: Promise<void>;
  act(() => { pending = result.current.submit(); });
  act(() => result.current.close());
  await act(() => result.current.submit());
  expect(result.current.visible).toBe(true);
  expect(result.current.busy).toBe(true);
  expect(mockApple).toHaveBeenCalledTimes(1);
  expect(mockDelete).not.toHaveBeenCalled();
  await act(async () => { authorize({ appleAuthorizationCode: "test-code" }); await pending; });
  expect(mockDelete).toHaveBeenCalledWith({ appleAuthorizationCode: "test-code" });
  expect(result.current.busy).toBe(false);
});
it.each(["apple", "api"])("keeps the account and typed text after %s failure, allowing retry", async source => {
  if (source === "apple") {
    mockProviders = ["APPLE"];
    mockApple.mockRejectedValueOnce(new Error("Cancelled"));
    mockApple.mockResolvedValue({ appleAuthorizationCode: "test-code" });
  } else mockDelete.mockRejectedValueOnce(new Error("Unavailable"));
  const deleted = jest.fn();
  const { result } = renderHook(() => usePermanentAccountDeletion(deleted));
  act(() => result.current.open());
  act(() => result.current.setText(mockPhrase));
  await act(() => result.current.submit());
  expect(result.current.visible).toBe(true);
  expect(result.current.text).toBe(mockPhrase);
  expect(result.current.busy).toBe(false);
  expect(mockClear).not.toHaveBeenCalled();
  expect(deleted).not.toHaveBeenCalled();
  expect(mockError).toHaveBeenCalledTimes(1);
  await act(() => result.current.submit());
  expect(mockClear).toHaveBeenCalledTimes(1);
});
it("explains that an organizer must cancel upcoming paid events first, and keeps the account", async () => {
  mockDelete.mockRejectedValueOnce(Object.assign(new Error("Cancel your upcoming events with paid tickets"), { code: "ORGANIZER_HAS_UPCOMING_PAID_EVENTS" }));
  const deleted = jest.fn();
  const { result } = renderHook(() => usePermanentAccountDeletion(deleted));
  act(() => result.current.open());
  act(() => result.current.setText(mockPhrase));
  await act(() => result.current.submit());
  expect(mockError).toHaveBeenCalledWith("profile.toastDeleteBlockedByPaidEvents");
  expect(mockClear).not.toHaveBeenCalled();
  expect(deleted).not.toHaveBeenCalled();
});
